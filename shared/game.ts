// Quick play: genre config and the game shape returned by /api/game.

export const GAME_LENGTH = 5;

/** One game song. Mirrors the client's PlayableTrack (audioId = Deezer ID). */
export interface GameTrack {
  id: string;
  audioId: string;
  title: string;
  artists: string[];
  album: string;
  coverUrl: string | null;
  durationMs: number;
  isrc: string | null;
  externalUrl: string;
  externalSite: "Deezer";
  year: number;
  /** 0 (obscure) – 1 (everyone knows it). */
  popularity: number;
}

export interface Game {
  tracks: GameTrack[];
  /** Every song in the selected genres (any year), for guess suggestions. */
  pool: { title: string; artist: string }[];
}

export interface GameSettings {
  genres: string[];
  from: number;
  to: number;
}

/** One song in server/catalog.ts, generated by scripts/build-catalog.ts. */
export interface CatalogSong {
  /** Deezer track ID. */
  id: number;
  title: string;
  artist: string;
  artistId: number;
  album: string;
  cover: string | null;
  /** Seconds. */
  duration: number;
  link: string;
  /** Original release year (not the remaster's). */
  year: number;
  popularity: number;
  genres: string[];
}

/** A game needs this many songs (by different artists) in range. */
export const MIN_SONGS = 10;

/**
 * The catalog only has songs from this year on. Deezer dates releases, not
 * songs, so a 1975 song on a 2011 remaster says 2011; for songs from 2000 on,
 * sourced from 2000s+ playlists, Deezer's year is reliable. Going earlier
 * needs original years from MusicBrainz: see scripts/build-catalog.ts.
 */
export const FIRST_YEAR = 2000;

